export function formatPrice(value: number) {
  return `UGX ${new Intl.NumberFormat('en-US', { maximumFractionDigits: 0 }).format(value)}`
}

export function monthlyPayment(price: number, months: number) {
  return Math.ceil(price / months / 100) * 100
}
